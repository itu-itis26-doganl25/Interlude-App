"""
Owner: E (Efe). ListeningEvent from the shared WBS-1.4 data model, recorded by the
players (WBS-12.1) and aggregated into musician statistics (WBS-12.2).
"""

from django.conf import settings
from django.db import models


class ListeningEvent(models.Model):
    class EventType(models.TextChoices):
        PLAY = "play", "Play"
        SKIP = "skip", "Skip"
        COMPLETE = "complete", "Complete"

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="listening_events",
    )
    song = models.ForeignKey(
        "catalogue.Song", on_delete=models.CASCADE, related_name="listening_events"
    )
    room = models.ForeignKey(
        "rooms.Room", on_delete=models.SET_NULL, null=True, blank=True, related_name="+"
    )
    event_type = models.CharField(max_length=16, choices=EventType.choices)
    position_seconds = models.PositiveIntegerField(default=0)
    # Generated by the player per playback action; makes client retries idempotent
    # (UC-15 A1: "each event is stored at most once").
    client_event_id = models.UUIDField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["song", "event_type", "created_at"])]
        constraints = [
            models.UniqueConstraint(
                fields=["user", "client_event_id"],
                condition=models.Q(client_event_id__isnull=False),
                name="unique_client_event_per_user",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.event_type} {self.song_id}"

    @property
    def context(self) -> str:
        """FR-35 playback context: individual playback or a listening room."""
        return "room" if self.room_id else "individual"
